import { PDFDocument } from "pdfkit";

export const generatePdf = async (data) => {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: "A4",
      margins: 40,
      info: {
        Author: "OneAI",
        Title: data.title,
        Creator: "OneAI",
      },
    });

    const chunks = [];

    doc.on("data", (chunk) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    // Title
    doc
      .fillColor("#111827")
      .fontSize(20)
      .text(data.title || "", {
        align: "center",
      });

    // Subtitle
    if (data.subtitle) {
      doc.moveDown(0.5);
      doc.fillColor("#6B7280").fontSize(12).text(data.subtitle, {
        align: "center",
      });
    }

    doc.moveDown(1.5);

    // Sections
    data?.sections?.forEach((s) => {
      doc
        .fillColor("#111827")
        .fontSize(16)
        .text(s.headings || "");

      doc.moveDown(0.5);

      s?.points?.forEach((p) => {
        doc.fillColor("#374151").fontSize(10).text(`• ${p}`, {
          lineGap: 3,
        });
      });

      // space
      doc.moveDown();
    });

    // Footer
    doc.fillColor("#9CA3AF").fontSize(12).opacity(0.8).text("Generated by OneAI", {
      align: "center",
    });

    doc.end();
  });
};
